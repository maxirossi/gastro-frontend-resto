import { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { restaurantLogin } from '../services/api';
import { saveRestaurantSession } from '../utils/auth';
import './Login.css';

function Login() {
  const [username, setUsername] = useState('');
  const [password, setPassword] = useState('');
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(false);
  const navigate = useNavigate();

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError('');
    setLoading(true);

    try {
      const response = await restaurantLogin({ username, password });
      
      // Guardar token y datos básicos
      // El username es el slug del restaurante
      saveRestaurantSession(response.token, {
        place_id: response.place_id,
        name: response.restaurant?.name,
        slug: response.restaurant?.slug || username,
      });

      // Redirigir al dashboard
      navigate('/resto/dashboard');
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Error al iniciar sesión');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="login-container">
      <div className="login-box">
        <h1>RosarioGastro</h1>
        <p style={{ textAlign: 'center', color: '#666', marginBottom: '2rem' }}>
          Admin de Restaurante
        </p>
        <form onSubmit={handleSubmit}>
          <div className="form-group">
            <label htmlFor="username">Usuario</label>
            <input
              type="text"
              id="username"
              value={username}
              onChange={(e) => setUsername(e.target.value)}
              required
              autoFocus
              disabled={loading}
            />
          </div>
          <div className="form-group">
            <label htmlFor="password">Contraseña</label>
            <input
              type="password"
              id="password"
              value={password}
              onChange={(e) => setPassword(e.target.value)}
              required
              disabled={loading}
            />
          </div>
          {error && <div className="error-message">{error}</div>}
          <button type="submit" className="login-button" disabled={loading}>
            {loading ? 'Iniciando sesión...' : 'Iniciar Sesión'}
          </button>
        </form>
      </div>
    </div>
  );
}

export default Login;

